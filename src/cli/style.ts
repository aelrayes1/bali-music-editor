/**
 * Bali Style Skill (v5 Phase 10) — approved preference memory.
 *
 *   npm run style -- report                               -> style/BALI_STYLE.md (the skill, generated from memory)
 *   npm run style -- explain --project p --subject B4     -> why a past selection was made (reads the record; changes nothing)
 *   npm run style -- advise --request request.json        -> a precedence-ordered, explained recommendation
 *   npm run style -- demo [--fixture tests/fixtures/style/future-project.json]  -> style/demo/future-project-demo.md
 *   npm run style -- record --decision d.json [--learn l.json]  -> record a HUMAN decision (and what it teaches)
 *
 * Style memory advises; it never edits a project, never overrides the current brief, and learns only
 * from explicit human decisions.
 */

import { existsSync } from "node:fs";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";
import { type AdviceRequest, type StyleContext, advise, confidence, derivedGeneral, effectivePreferences, explainSelection, loadStyle, recordDecision } from "../style/engine.ts";
import type { Learning } from "../style/engine.ts";
import { writeJson } from "./project.ts";

const { values, positionals } = parseArgs({ allowPositionals: true, options: { dir: { type: "string", default: "style/bali" }, project: { type: "string" }, subject: { type: "string" }, request: { type: "string" }, fixture: { type: "string", default: "tests/fixtures/style/future-project.json" }, decision: { type: "string" }, learn: { type: "string" } } });
const DIR = values.dir!;
const read = async (p: string) => JSON.parse(await readFile(p, "utf8"));

export async function loadStyleDir(dir: string): Promise<StyleContext> {
  const logs = (await readdir(path.join(dir, "decisions"))).filter((f) => f.endsWith(".json")).sort();
  return loadStyle(await read(path.join(dir, "memory.json")), await Promise.all(logs.map((f) => read(path.join(dir, "decisions", f)))));
}

const ctx = await loadStyleDir(DIR);
const mode = positionals[0];

function adviceMd(a: ReturnType<typeof advise>, title: string): string[] {
  return [
    `### ${title}`, "",
    `**${a.question} → \`${a.recommended ?? "none"}\`**`, "",
    a.explanation, "",
    ...(a.eliminated.length ? ["Eliminated by precedence:", ...a.eliminated.map((e) => `- \`${e.optionId}\` — ${e.level} (${e.by}): ${e.why}`), ""] : []),
    "Ranking of the remaining options (project preferences, then Bali general, then order):", ...a.ranking.map((r) => `- \`${r.optionId}\`: project ${r.project >= 0 ? "+" : ""}${r.project}, general ${r.general >= 0 ? "+" : ""}${r.general}`), "",
    "Why:", ...a.reasons.map((r) => `- ${r.level} · \`${r.source}\` — ${r.statement} (${r.effect})${r.provenance ? `<br>provenance: ${r.provenance}` : ""}`), "",
    ...(a.overridden.length ? ["Stored taste that was overruled:", ...a.overridden.map((o) => `- \`${o.preference}\` — ${o.why}`), ""] : []),
    ...(a.warnings.length ? ["Warnings:", ...a.warnings.map((w) => `- ${w}`), ""] : []),
  ];
}

if (mode === "report") {
  const m = ctx.memory;
  const gen = m.preferences.filter((p) => p.scope === "BALI_GENERAL" && p.status === "ACTIVE");
  const projects = [...new Set(m.preferences.filter((p) => p.scope === "PROJECT_SPECIFIC").map((p) => p.projectId!))].sort();
  const L = [
    "# Bali Style Skill — approved preference memory", "",
    `> Generated by \`npm run style -- report\` from \`${DIR}/\` (memory v${m.version}, updated ${m.updated}, sha \`${ctx.sha256.slice(0, 16)}\`). Do not edit by hand: record human decisions instead.`, "",
    "> v5 gate: **style memory must accelerate taste without overfitting or overriding the brief.** It advises; the current brief and current human instructions always win.", "",
    "## How to use it", "",
    "1. Precedence (`policy:precedence`): **current human override > project hard constraint > technical safety / QC > approved project preference > Bali general preference > default heuristic.**",
    "2. Ask: `npm run style -- advise --request <json>` → a recommendation that names every preference used and where it came from.",
    "3. Explain a past choice: `npm run style -- explain --project <p> --subject <id>`.",
    "4. Learn only from human decisions: `npm run style -- record --decision <json> [--learn <json>]`. Metrics never create taste.", "",
    "## Technical rules (objective; verified by QC, never taste)", "",
    ...m.technicalRules.map((r) => `- \`${r.id}\` — ${r.statement} _(checks: ${r.enforcedBy.join(", ")})_`), "",
    "## Policies", "", ...m.policies.map((p) => `- \`${p.id}\` — ${p.statement} _(source: ${p.source.ref})_`), "",
    "## Bali general preferences", "",
    "| id | polarity | statement | applies to | origin / confidence | evidence |", "| --- | --- | --- | --- | --- | --- |",
    ...gen.map((p) => `| \`${p.id}\` | ${p.polarity} | ${p.statement}${p.when.length ? ` _(when ${p.when.map((c) => `${c.property} ${c.op} ${c.value}`).join(", ")})_` : ""}${p.note ? ` _(${p.note})_` : ""} | ${p.appliesTo.join(", ")} | ${p.origin} / ${confidence(p, ctx.decisions).level} | ${p.evidence.map((e) => e.decisionId).join(", ")} |`), "",
    ...(derivedGeneral(ctx).length ? ["Promoted by repeated evidence (>= 3 projects):", ...derivedGeneral(ctx).map((p) => `- \`${p.id}\` — ${p.statement} (${p.note})`), ""] : ["Promoted by repeated evidence (>= 3 projects): none yet.", ""]),
    "## Project-specific preferences (never applied to other projects)", "",
    ...projects.flatMap((pid) => [`### ${pid}`, "", "| id | polarity | statement | confidence | evidence |", "| --- | --- | --- | --- | --- |", ...m.preferences.filter((p) => p.projectId === pid && p.status === "ACTIVE").map((p) => `| \`${p.id}\` | ${p.polarity} | ${p.statement} | ${confidence(p, ctx.decisions).level} (${confidence(p, ctx.decisions).why}) | ${p.evidence.map((e) => e.decisionId).join(", ")} |`), ""]),
    "## Presets (v5; qualitative, not yet calibrated on approved projects)", "",
    ...m.presets.map((p) => `- **${p.name}** (${p.status}${p.approvedOn.length ? `, approved on ${p.approvedOn.join(", ")}` : ""}) — ${p.intent}. Pacing: ${p.pacing}. FX: ${p.fx}. Arc: ${p.energyArc}. Subject: ${p.subject}. Uses ${p.preferenceIds.map((x) => `\`${x}\``).join(", ")}.`), "",
    "## Conflicts / updates", "", ...(m.conflicts.length ? m.conflicts.map((c) => `- ${c.date} \`${c.preferenceId}\` ← ${c.decisionId}: ${c.resolution} — ${c.note}`) : ["- none recorded"]), "",
    "## Human decision log", "", ...ctx.decisions.map((d) => `- \`${d.id}\` ${d.date} ${d.kind} (${d.projectId}) — ${d.subject}: ${d.statement}`), "",
  ];
  await writeFile("style/BALI_STYLE.md", L.join("\n"));
  console.log(`wrote style/BALI_STYLE.md (${gen.length} general preferences, ${projects.length} project(s), sha ${ctx.sha256.slice(0, 16)})`);
} else if (mode === "explain") {
  if (!values.project || !values.subject) throw new Error("explain needs --project and --subject");
  const x = explainSelection(ctx, values.project, values.subject);
  const L = [`# Why ${values.subject} — ${values.project}`, "", `> Reconstructed from the human decision log by \`npm run style -- explain\`; the edit is not changed.`, "", ...x.lines.slice(1, x.chain.length + 1), "", "## Preferences these decisions support", "", ...x.preferences.map((p) => `- \`${p.id}\` (${p.polarity}${p.status === "SUPERSEDED" ? `; **SUPERSEDED** by \`${p.supersededBy}\`` : ""}) — ${p.statement}<br>${p.provenance}`), "", "## Policies that governed the decision", "", ...x.policies.map((p) => `- ${p}`), ""];
  await mkdir("style/explanations", { recursive: true });
  const out = `style/explanations/${values.project}-${values.subject.replace(/[^\w-]+/g, "_")}.md`;
  await writeFile(out, L.join("\n"));
  console.log(x.lines.join("\n"));
  console.log(`wrote ${out}`);
} else if (mode === "advise") {
  if (!values.request) throw new Error("advise needs --request <json>");
  const a = advise(ctx, (await read(values.request)) as AdviceRequest);
  console.log(JSON.stringify(a, null, 2));
} else if (mode === "demo") {
  const fx = await read(values.fixture!);
  const L = [`# Future-project demonstration (synthetic fixture \`${fx.projectId}\`)`, "", `> ${fx.note}`, "", `Generated by \`npm run style -- demo\` from \`${values.fixture}\` and style memory sha \`${ctx.sha256.slice(0, 16)}\`. Nothing is persisted and no real project is touched.`, ""];
  const eff = effectivePreferences(ctx, fx.projectId);
  L.push("## Scope", "", `- ${fx.projectId} sees ${eff.preferences.length} preferences (Bali general + its own); ${eff.excludedOtherProjects} project-specific preferences of other projects (e.g. reference-project) are excluded.`, "");
  L.push("## Recommendations", "");
  const results: Record<string, unknown> = {};
  for (const r of fx.requests as Array<{ id: string; title: string; request: AdviceRequest }>) {
    const a = advise(ctx, r.request);
    results[r.id] = a;
    L.push(...adviceMd(a, r.title));
  }
  const rec = recordDecision(ctx, fx.contradiction.decision, fx.contradiction.learn as Learning);
  const after = { ...ctx, memory: rec.memory, decisions: rec.decisions };
  const again = advise(after, (fx.requests as Array<{ id: string; request: AdviceRequest }>).find((r) => r.id === "general-taste")!.request);
  const elsewhere = advise(after, { ...(fx.requests as Array<{ id: string; request: AdviceRequest }>).find((r) => r.id === "general-taste")!.request, projectId: "fixture-another-project" });
  L.push("## Contradiction: a new explicit decision against stored taste", "", `Decision \`${fx.contradiction.decision.id}\`: “${fx.contradiction.decision.quote}”`, "", ...rec.changes.map((c) => `- ${c}`), "", `- In ${fx.projectId} the same question now → \`${again.recommended}\` (${again.overridden.filter((o) => o.level === "APPROVED_PROJECT_PREFERENCE").map((o) => o.why).join("; ")}).`, `- In another project it is still → \`${elsewhere.recommended}\`: general taste did not change from one project.`, "");
  await mkdir("style/demo", { recursive: true });
  await writeFile("style/demo/future-project-demo.md", L.join("\n"));
  await writeJson("style/demo/future-project-demo.json", { memorySha256: ctx.sha256, fixture: values.fixture, results, contradiction: { changes: rec.changes, conflicts: rec.memory.conflicts, afterRecommendation: again.recommended, elsewhereRecommendation: elsewhere.recommended } });
  console.log(`wrote style/demo/future-project-demo.{md,json}`);
} else if (mode === "record") {
  if (!values.decision) throw new Error("record needs --decision <json>");
  const d = await read(values.decision);
  const rec = recordDecision(ctx, d, values.learn ? await read(values.learn) : null);
  const logFile = path.join(DIR, "decisions", `${d.projectId}.json`);
  const log = existsSync(logFile) ? await read(logFile) : { schemaVersion: "1.0.0", kind: "HUMAN_DECISION_LOG", projectId: d.projectId, decisions: [] };
  log.decisions.push(rec.decisions.find((x) => x.id === d.id));
  await writeJson(logFile, log);
  await writeJson(path.join(DIR, "memory.json"), rec.memory);
  await loadStyleDir(DIR); // full re-validation: every preference still traces to a recorded human decision
  console.log(rec.changes.join("\n") || "recorded (no preference change)");
} else {
  throw new Error("usage: style report | explain --project p --subject s | advise --request f | demo | record --decision f [--learn f]");
}
