/**
 * Human-verifiable diagnostics for a music analysis window.
 *
 *  - <name>.md                   timeline, detailed event table, proposed pattern sync targets
 *  - <name>.png                  visual timeline (rendered from SVG by the verified FFmpeg)
 *  - <pattern>-overlay.wav       the window with clicks on each candidate (listen-through check)
 *  - <pattern>-sequence.wav      every candidate isolated, in order (one-by-one check)
 *
 * Derived audio is written only into the diagnostics directory; the original is never touched.
 */

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { type MediaTools, runFfmpeg } from "../media/ffmpeg.ts";
import { type Rational, compare, toNumberApprox } from "../time/rational.ts";
import { literalToSeconds, parseTimeLiteral } from "../time/time.ts";
import { SAMPLE_RATE } from "./features.ts";
import type { MusicAnalysis, MusicSync, ResolvedEvent, ResolvedMusicEvents } from "./schema.ts";

export interface DiagnosticsWindow {
  name: string;
  context: { start: string; end: string };
  table: { start: string; end: string };
  patternId: string | null;
}

const sec = (lit: string) => literalToSeconds(parseTimeLiteral(lit));
const num = (r: Rational) => toNumberApprox(r);
const within = (t: Rational, a: Rational, b: Rational) => compare(t, a) >= 0 && compare(t, b) < 0;

export function clock(t: number): string {
  const ms = Math.round(t * 1000);
  const m = Math.floor(ms / 60000);
  const s = ((ms % 60000) / 1000).toFixed(3).padStart(6, "0");
  return `${m}:${s}`;
}

function curveAt(values: number[], t: number): number | null {
  const i = Math.floor(t * 10);
  return i >= 0 && i < values.length ? values[i]! : null;
}

function beatRelation(a: MusicAnalysis, e: { nearestBeatId: string | null; beatOffsetMs: number | null }): string {
  if (!e.nearestBeatId) return "-";
  const b = a.beats.find((x) => x.id === e.nearestBeatId);
  if (!b) return e.nearestBeatId;
  const off = e.beatOffsetMs ?? 0;
  const sign = off >= 0 ? "+" : "−";
  return `bar ${b.barIndex}.${b.beatInBar}${b.isDownbeat ? " (downbeat)" : ""} ${sign}${Math.abs(off).toFixed(1)} ms`;
}

function nearestOnsetStrength(a: MusicAnalysis, t: Rational): number | null {
  let best: number | null = null;
  let bestD = Infinity;
  const tt = num(t);
  for (const e of a.events) {
    if (e.type !== "onset") continue;
    const d = Math.abs(num(e.time) - tt);
    if (d < bestD && d <= 0.03) {
      bestD = d;
      best = e.strength;
    }
  }
  return best;
}

