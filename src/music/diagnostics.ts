function tick(buf: Float32Array, at: number, hz: number, seconds: number, gain: number): void {
  const n = Math.round(seconds * SAMPLE_RATE);
  for (let i = 0; i < n; i++) {
    const s = at + i;
    if (s < 0 || s >= buf.length) continue;
    buf[s] = buf[s]! + gain * Math.sin((2 * Math.PI * hz * i) / SAMPLE_RATE) * Math.exp(-i / (n / 4));
  }
}

export function wav16(samples: Float32Array): Buffer {
  let peak = 0;
  for (const v of samples) peak = Math.max(peak, Math.abs(v));
  const scale = peak > 0.99 ? 0.99 / peak : 1;
  const data = Buffer.alloc(samples.length * 2);
  for (let i = 0; i < samples.length; i++) data.writeInt16LE(Math.round(Math.max(-1, Math.min(1, samples[i]! * scale)) * 32767), i * 2);
  const h = Buffer.alloc(44);
  h.write("RIFF", 0);
  h.writeUInt32LE(36 + data.length, 4);
  h.write("WAVEfmt ", 8);
  h.writeUInt32LE(16, 16);
  h.writeUInt16LE(1, 20);
  h.writeUInt16LE(1, 22);
  h.writeUInt32LE(SAMPLE_RATE, 24);
  h.writeUInt32LE(SAMPLE_RATE * 2, 28);
  h.writeUInt16LE(2, 32);
  h.writeUInt16LE(16, 34);
  h.write("data", 36);
  h.writeUInt32LE(data.length, 40);
  return Buffer.concat([h, data]);
}

export function overlayAudio(samples: Float32Array, w: DiagnosticsWindow, candidates: ResolvedEvent[], userEvents: ResolvedEvent[]): Float32Array {
  const s0 = Math.round(num(sec(w.context.start)) * SAMPLE_RATE);
  const s1 = Math.round(num(sec(w.context.end)) * SAMPLE_RATE);
  const buf = samples.slice(s0, s1).map((v) => v * 0.6);
  for (const c of candidates) {
    const at = Math.round(num(c.time) * SAMPLE_RATE) - s0;
    if (c.identityStatus === "HIGH_CONFIDENCE_CANDIDATE" || c.identityStatus === "CONFIRMED") tick(buf, at, 2400, 0.03, 0.45);
    else tick(buf, at, 900, 0.03, 0.4);
  }
  for (const u of userEvents) tick(buf, Math.round(num(u.time) * SAMPLE_RATE) - s0, 440, 0.25, 0.35);
  return buf;
}

export function sequenceAudio(samples: Float32Array, candidates: ResolvedEvent[]): { audio: Float32Array; index: Array<{ id: string; at: number }> } {
  const pre = Math.round(0.12 * SAMPLE_RATE);
  const post = Math.round(0.6 * SAMPLE_RATE);
  const gap = Math.round(0.35 * SAMPLE_RATE);
  const parts: Float32Array[] = [];
  const index: Array<{ id: string; at: number }> = [];
  let cursor = 0;
  for (const c of candidates) {
    const at = Math.round(num(c.time) * SAMPLE_RATE);
    const seg = samples.slice(Math.max(0, at - pre), Math.min(samples.length, at + post));
    const fade = Math.round(0.005 * SAMPLE_RATE);
    for (let i = 0; i < fade && i < seg.length; i++) {
      seg[i] = seg[i]! * (i / fade);
      seg[seg.length - 1 - i] = seg[seg.length - 1 - i]! * (i / fade);
    }
    index.push({ id: c.id, at: (cursor + pre) / SAMPLE_RATE });
    parts.push(seg, new Float32Array(gap));
    cursor += seg.length + gap;
  }
  const audio = new Float32Array(cursor);
  let o = 0;
  for (const p of parts) {
    audio.set(p, o);
    o += p.length;
  }
  return { audio, index };
}

export async function writeDiagnostics(
  tools: MediaTools,
  a: MusicAnalysis,
  r: ResolvedMusicEvents,
  sync: MusicSync | null,
  samples: Float32Array,
  w: DiagnosticsWindow,
  outDir: string,
): Promise<string[]> {
  await mkdir(outDir, { recursive: true });
  const written: string[] = [];
  const cands = w.patternId ? r.events.filter((e) => e.patternId === w.patternId) : [];
  const users = r.events.filter((e) => e.origin === "user");
  let overlay: string | null = null;
  let sequence: string | null = null;
  let sequenceIndex: Array<{ id: string; at: number }> = [];
  if (w.patternId) {
    const tag = w.patternId.replace(/^usr:/, "");
    overlay = path.join(outDir, `${w.name}-${tag}-overlay.wav`);
    await writeFile(overlay, wav16(overlayAudio(samples, w, cands, users)));
    const seq = sequenceAudio(samples, cands);
    sequence = path.join(outDir, `${w.name}-${tag}-sequence.wav`);
    await writeFile(sequence, wav16(seq.audio));
    sequenceIndex = seq.index;
    written.push(overlay, sequence);
  }
  const md = path.join(outDir, `${w.name}.md`);
  await writeFile(md, windowReport(a, r, sync, w, { overlay, sequence, sequenceIndex }));
  const svg = path.join(outDir, `${w.name}.svg`);
  await writeFile(svg, windowSvg(a, r, samples, w));
  const png = path.join(outDir, `${w.name}.png`);
  await runFfmpeg(tools, ["-hide_banner", "-nostdin", "-v", "error", "-i", svg, "-frames:v", "1", "-y", png]);
  written.unshift(md, png, svg);
  return written;
}
