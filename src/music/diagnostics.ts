export function windowReport(
  a: MusicAnalysis,
  r: ResolvedMusicEvents,
  sync: MusicSync | null,
  w: DiagnosticsWindow,
  audioFiles: { overlay: string | null; sequence: string | null; sequenceIndex: Array<{ id: string; at: number }> },
): string {
  const cs = sec(w.context.start);
  const ce = sec(w.context.end);
  const ts = sec(w.table.start);
  const te = sec(w.table.end);
  const L: string[] = [];
  const bpm = num(a.tempo.canonicalBpm);
  L.push(`# Music diagnostics — ${a.source.fileName}`, "");
  L.push(`Window ${clock(num(cs))}–${clock(num(ce))} · detailed table ${clock(num(ts))}–${clock(num(te))}`, "");
  L.push("> Generated by the music analyzer. **Nothing here chooses footage or creates cuts.** Verify the events (especially vocal candidates) before they drive an edit.", "");
  L.push("## Track summary", "");
  L.push(`| | |`, `|---|---|`);
  L.push(`| Media ID | \`${a.source.mediaId}\` (audio stream ${a.source.audioStreamIndex}; cover art ignored) |`);
  L.push(`| Duration | ${clock(num(a.durationSeconds))} |`);
  L.push(`| Tempo | **${a.tempo.canonicalBpm.num}/${a.tempo.canonicalBpm.den} BPM** (${a.tempo.snapRule}); measured ${bpm === num(a.tempo.measuredBpm) ? "identical" : num(a.tempo.measuredBpm).toFixed(4)}; confidence ${a.tempo.bpmConfidence}; kick-beat support ${a.tempo.support}; residual ${a.tempo.residualRmsMs} ms; drift ${a.tempo.constantTempo.driftMsPerMinute} ms/min |`);
  L.push(`| Beat grid | beat *i* = ${num(a.tempo.gridAnchorSeconds).toFixed(6)} s + *i* × ${a.tempo.beatPeriodSeconds.num}/${a.tempo.beatPeriodSeconds.den} s (exact rationals, no accumulation) |`);
  L.push(`| Meter | ${a.meter.beatsPerBar}/4, downbeat phase ${a.meter.downbeatPhase} (margin ${a.meter.downbeatConfidence}); ${a.meter.phraseBars}-bar phrases from bar ${a.meter.phrasePhaseBars} (margin ${a.meter.phraseConfidence}) |`);
  L.push(`| Loudness | ${a.curves.loudness.integratedLufs} LUFS integrated, LRA ${a.curves.loudness.loudnessRangeLu} LU, true peak ${a.curves.loudness.truePeakDbtp} dBTP (EBU R128 via FFmpeg) |`);
  L.push(`| Warnings | ${a.warnings.map((x) => `\`${x.code}\``).join(", ") || "none"} |`);
  L.push("");

  // Timeline
  L.push(`## Timeline ${clock(num(cs))}–${clock(num(ce))}`, "");
  type Row = { t: number; text: string };
  const rows: Row[] = [];
  for (const b of a.bars.filter((x) => within(x.time, cs, ce))) {
    rows.push({ t: num(b.time), text: `bar ${b.index} downbeat (\`${b.id}\`) — energy ${b.energyDb} dB (${b.energyLevel}, ${b.trend})` });
  }
  for (const p of a.phrases.filter((x) => within(x.time, cs, ce))) {
    rows.push({ t: num(p.time), text: `**phrase boundary** \`${p.id}\` (${p.lengthBars}-bar phrases, confidence ${p.confidence})` });
  }
  for (const s of a.sections.filter((x) => within(x.start, cs, ce))) {
    rows.push({ t: num(s.start), text: `section \`${s.id}\` **${s.label}** (${s.energyLevel}, ${s.trend}; confidence ${s.confidence}; ${s.evidence})` });
  }
  for (const g of a.regions.filter((x) => x.type !== "vocal_activity" && (within(x.start, cs, ce) || within(x.end, cs, ce)))) {
    rows.push({ t: num(g.start), text: `**${g.type}** \`${g.id}\` ${clock(num(g.start))}–${clock(num(g.end))} (confidence ${g.confidence}; ${g.detail})` });
  }
  for (const e of a.events.filter((x) => (x.type === "drop" || x.type === "impact") && within(x.time, cs, ce))) {
    rows.push({ t: num(e.time), text: `**${e.type}** \`${e.id}\` (confidence ${e.confidence}; ${e.detail}; ${beatRelation(a, e)})` });
  }
  for (const e of r.events.filter((x) => x.origin === "user" && within(x.time, cs, ce))) {
    rows.push({ t: num(e.time), text: `**USER ${e.type}** \`${e.id}\` — ${e.label} (${beatRelation(a, e)})` });
  }
  const vocalN = r.events.filter((x) => x.patternId && within(x.time, cs, ce)).length;
  rows.sort((x, y) => x.t - y.t || x.text.localeCompare(y.text));
  for (const row of rows) L.push(`- \`${clock(row.t)}\` ${row.text}`);
  L.push("", `Vocal/tonal attack candidates in the pattern window: ${vocalN} (listed below).`, "");

  // Detailed table
  L.push(`## Event table ${clock(num(ts))}–${clock(num(te))}`, "");
  L.push("| Time | Event ID | Type | Beat / bar relation | Transient | Energy (dBFS) | Vocal status | User-required | Confidence |");
  L.push("|---|---|---|---|---|---|---|---|---|");
  const tableEvents = r.events.filter(
    (e) => within(e.time, ts, te) && (e.tier !== "DETAIL" || e.type === "vocal_attack"),
  );
  for (const e of tableEvents) {
    const t = num(e.time);
    const tr = nearestOnsetStrength(a, e.time);
    const en = curveAt(a.curves.energy.rmsDbfs, t);
    const vocal = e.type === "vocal_attack" ? (e.identityStatus ?? "candidate (not in pattern window)") : "-";
    const required = e.mandatory ? (e.origin === "user" ? "**yes (user)**" : `**yes (${e.patternId})**`) : "no";
    L.push(
      `| ${clock(t)} | \`${e.id}\` | ${e.type} | ${beatRelation(a, e)} | ${tr === null ? "-" : tr.toFixed(2)} | ${en === null ? "-" : en.toFixed(1)} | ${vocal} | ${required} | ${e.confidence.toFixed(2)} |`,
    );
  }
  L.push("");

  // Pattern candidates
  if (w.patternId && sync) {
    const pattern = sync.requiredPatterns.find((p) => p.id === w.patternId);
    const cands = r.events.filter((e) => e.patternId === w.patternId);
    const label = pattern?.label ?? w.patternId;
    L.push(`## PROPOSED “${label.toUpperCase()}” SYNC TARGETS`, "");
    if (pattern) L.push(`Requirement: **every occurrence** of “${label}” between ${pattern.window.start} and ${pattern.window.end} is a mandatory visual sync target.`, "");
    L.push(
      "**Word identity is not verified by software.** No local speech recognition is installed and none was downloaded. Candidates are tonal (formant-band) attacks; status means:",
      "",
      "- `CONFIRMED` — a human confirmed it (none yet).",
      "- `HIGH_CONFIDENCE_CANDIDATE` — strongest repeating tonal attack pattern in the window (similarity ≥ 0.85 to its medoid, clear harmonic content, ≥ 5 dB formant rise). Consistent with a repeated word; still unverified.",
      "- `NEEDS_HUMAN_CONFIRMATION` — tonal attack that could be the word, a second syllable, another word or a synth stab.",
      "",
    );
    const counts = { CONFIRMED: 0, HIGH_CONFIDENCE_CANDIDATE: 0, NEEDS_HUMAN_CONFIRMATION: 0 } as Record<string, number>;
    for (const c of cands) counts[c.identityStatus ?? "NEEDS_HUMAN_CONFIRMATION"]!++;
    L.push(`Totals: ${cands.length} candidates — ${counts.CONFIRMED} confirmed, ${counts.HIGH_CONFIDENCE_CANDIDATE} high-confidence, ${counts.NEEDS_HUMAN_CONFIRMATION} need confirmation.`, "");
    L.push("| # | Time | Event ID | Status | Confidence | Beat / bar relation | Evidence | In sequence WAV at |");
    L.push("|---|---|---|---|---|---|---|---|");
    cands.forEach((c, i) => {
      const at = audioFiles.sequenceIndex.find((x) => x.id === c.id)?.at;
      L.push(
        `| ${i + 1} | **${clock(num(c.time))}** | \`${c.id}\` | ${c.identityStatus} | ${c.confidence.toFixed(2)} | ${beatRelation(a, c)} | ${c.evidence ?? ""} | ${at === undefined ? "-" : `${at.toFixed(2)} s`} |`,
      );
    });
    L.push("");
    L.push("### How to verify", "");
    if (audioFiles.overlay) L.push(`1. Listen to \`${path.basename(audioFiles.overlay)}\` (${w.context.start}–${w.context.end}): **high tick** = high-confidence candidate, **low tick** = needs confirmation, **long tone** = your boundary events.`);
    if (audioFiles.sequence) L.push(`2. Listen to \`${path.basename(audioFiles.sequence)}\`: each candidate is played alone (0.12 s before → 0.6 s after its attack) in table order; the table gives its start time in that file.`);
    L.push(
      "3. Record decisions in `projects/…/music-sync.json` → `eventOverrides` (the analyzer output is never edited):",
      "",
      "```json",
      '{ "id": "usr:confirm-1", "targetEventId": "vocal:<sample>", "action": "confirm", "note": "is \\"hook\\"" }',
      '{ "id": "usr:not-word-2", "targetEventId": "vocal:<sample>", "action": "exclude", "note": "second syllable" }',
      '{ "id": "usr:fix-3", "targetEventId": "vocal:<sample>", "action": "retime", "time": "00:01:22.690" }',
      '{ "id": "usr:missing-4", "type": "vocal_hit", "time": "00:01:27.410", "label": "hook" }   ← add to requiredEvents',
      "```",
      "",
    );
  }
  return L.join("\n") + "\n";
}

