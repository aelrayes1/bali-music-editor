export function windowSvg(
  a: MusicAnalysis,
  r: ResolvedMusicEvents,
  samples: Float32Array,
  w: DiagnosticsWindow,
): string {
  const t0 = num(sec(w.context.start));
  const t1 = num(sec(w.context.end));
  const W = 2400;
  const X0 = 70;
  const plotW = W - X0 - 20;
  const x = (t: number) => X0 + ((t - t0) / (t1 - t0)) * plotW;
  const H = 820;
  const lanes = { wave: [40, 230], energy: [250, 420], onset: [440, 560], vocal: [580, 740] } as const;
  const out: string[] = [];
  out.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" font-family="Menlo, monospace" font-size="15">`);
  out.push(`<rect width="${W}" height="${H}" fill="#101014"/>`);
  out.push(`<text x="${X0}" y="26" fill="#ddd" font-size="18">${a.source.fileName} · ${clock(t0)}–${clock(t1)} · ${a.tempo.canonicalBpm.num}/${a.tempo.canonicalBpm.den} BPM</text>`);

  // Regions shading
  for (const g of a.regions) {
    if (g.type === "vocal_activity" || num(g.end) < t0 || num(g.start) > t1) continue;
    const color = g.type === "break" ? "#5a1f24" : g.type === "build" ? "#5a3f16" : g.type === "fill" ? "#1f3f5a" : "#333";
    out.push(`<rect x="${x(Math.max(t0, num(g.start)))}" y="40" width="${Math.max(1, x(Math.min(t1, num(g.end))) - x(Math.max(t0, num(g.start))))}" height="${H - 90}" fill="${color}" opacity="0.55"/>`);
    out.push(`<text x="${x(Math.max(t0, num(g.start))) + 4}" y="${H - 58}" fill="#e9a" font-size="14">${g.type}</text>`);
  }

  // Beat grid
  for (const b of a.beats) {
    const t = num(b.time);
    if (t < t0 || t > t1) continue;
    out.push(`<line x1="${x(t)}" y1="40" x2="${x(t)}" y2="${H - 50}" stroke="${b.isDownbeat ? "#777" : "#333"}" stroke-width="${b.isDownbeat ? 2 : 1}"/>`);
    if (b.isDownbeat) out.push(`<text x="${x(t) + 3}" y="${H - 36}" fill="#aaa" font-size="13">bar ${b.barIndex}</text>`);
  }
  for (const p of a.phrases) {
    const t = num(p.time);
    if (t >= t0 && t <= t1) out.push(`<line x1="${x(t)}" y1="40" x2="${x(t)}" y2="${H - 50}" stroke="#4a8cff" stroke-width="3"/>`);
  }

  // Waveform envelope
  const [wy0, wy1] = lanes.wave;
  const mid = (wy0 + wy1) / 2;
  const half = (wy1 - wy0) / 2;
  const s0 = Math.round(t0 * SAMPLE_RATE);
  const perPx = ((t1 - t0) * SAMPLE_RATE) / plotW;
  const path1: string[] = [];
  for (let px = 0; px < plotW; px++) {
    let mn = 0;
    let mx = 0;
    for (let i = Math.floor(s0 + px * perPx); i < Math.floor(s0 + (px + 1) * perPx) && i < samples.length; i++) {
      const v = samples[i]!;
      if (v < mn) mn = v;
      if (v > mx) mx = v;
    }
    path1.push(`M${X0 + px} ${(mid - mx * half).toFixed(1)}V${(mid - mn * half).toFixed(1)}`);
  }
  out.push(`<path d="${path1.join("")}" stroke="#9cc" stroke-width="1"/>`);
  out.push(`<text x="8" y="${mid}" fill="#9cc">wave</text>`);

  // Energy curves
  const [ey0, ey1] = lanes.energy;
  const lineFor = (vals: number[], lo: number, hi: number, color: string, label: string, dy: number) => {
    const pts: string[] = [];
    for (let i = Math.floor(t0 * 10); i <= Math.ceil(t1 * 10) && i < vals.length; i++) {
      const v = Math.max(lo, Math.min(hi, vals[i]!));
      pts.push(`${x(i / 10).toFixed(1)},${(ey1 - ((v - lo) / (hi - lo)) * (ey1 - ey0)).toFixed(1)}`);
    }
    out.push(`<polyline points="${pts.join(" ")}" fill="none" stroke="${color}" stroke-width="2"/>`);
    out.push(`<text x="8" y="${ey0 + dy}" fill="${color}" font-size="13">${label}</text>`);
  };
  lineFor(a.curves.energy.rmsDbfs, -40, 0, "#eee", "rms", 16);
  const lowVals = a.curves.energy.lowDb;
  const lowMax = Math.max(...lowVals.slice(Math.floor(t0 * 10), Math.ceil(t1 * 10)));
  lineFor(lowVals, lowMax - 30, lowMax, "#f66", "low", 34);
  const highVals = a.curves.energy.highDb;
  const highMax = Math.max(...highVals.slice(Math.floor(t0 * 10), Math.ceil(t1 * 10)));
  lineFor(highVals, highMax - 30, highMax, "#fd6", "high", 52);

  // Onsets
  const [oy0, oy1] = lanes.onset;
  for (const e of a.events) {
    const t = num(e.time);
    if (e.type !== "onset" || t < t0 || t > t1) continue;
    const hgt = Math.min(1.5, e.strength) / 1.5 * (oy1 - oy0);
    out.push(`<line x1="${x(t)}" y1="${oy1}" x2="${x(t)}" y2="${oy1 - hgt}" stroke="${e.detail ? "#f88" : "#999"}" stroke-width="2"/>`);
  }
  out.push(`<text x="8" y="${(oy0 + oy1) / 2}" fill="#999">onsets</text>`);

  // Vocal candidates
  const [vy0, vy1] = lanes.vocal;
  out.push(`<text x="8" y="${(vy0 + vy1) / 2}" fill="#fb4">vocal</text>`);
  let idx = 0;
  for (const e of r.events) {
    const t = num(e.time);
    if (e.type !== "vocal_attack" || t < t0 || t > t1) continue;
    const color = e.identityStatus === "CONFIRMED" ? "#4f4" : e.identityStatus === "HIGH_CONFIDENCE_CANDIDATE" ? "#fa3" : e.identityStatus === "NEEDS_HUMAN_CONFIRMATION" ? "#ee6" : "#665";
    const hgt = Math.max(0.2, e.confidence) * (vy1 - vy0);
    out.push(`<line x1="${x(t)}" y1="${vy1}" x2="${x(t)}" y2="${vy1 - hgt}" stroke="${color}" stroke-width="${e.patternId ? 4 : 2}"/>`);
    if (e.patternId) {
      idx++;
      out.push(`<text x="${x(t) - 6}" y="${vy1 - hgt - 6}" fill="${color}" font-size="13">${idx}</text>`);
    }
  }

  // Drops and user events on top
  for (const e of a.events) {
    const t = num(e.time);
    if (e.type === "drop" && t >= t0 && t <= t1) {
      out.push(`<line x1="${x(t)}" y1="40" x2="${x(t)}" y2="${H - 50}" stroke="#f33" stroke-width="5"/>`);
      out.push(`<text x="${x(t) + 6}" y="60" fill="#f55" font-size="16">DROP ${clock(t)}</text>`);
    }
  }
  for (const e of r.events.filter((x) => x.origin === "user")) {
    const t = num(e.time);
    if (t < t0 || t > t1) continue;
    out.push(`<line x1="${x(t)}" y1="40" x2="${x(t)}" y2="${H - 50}" stroke="#e5f" stroke-width="3" stroke-dasharray="10,6"/>`);
    out.push(`<text x="${x(t) + 6}" y="${e.type === "structural_boundary" ? 82 : 104}" fill="#e7f" font-size="15">${e.id} ${clock(t)}</text>`);
  }

  // Time axis
  for (let t = Math.ceil(t0); t <= t1; t++) {
    out.push(`<text x="${x(t) - 20}" y="${H - 14}" fill="#ccc" font-size="14">${clock(t).slice(0, -4)}</text>`);
  }
  out.push(`<text x="${W - 900}" y="26" fill="#aaa" font-size="14">blue=phrase  red=drop  magenta=user event  orange=high-conf candidate  yellow=needs confirmation</text>`);
  out.push("</svg>");
  return out.join("\n");
}

